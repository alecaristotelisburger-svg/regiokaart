"""Test van de nieuwe huisstijl (body.nieuw): balk links, panelen, compacte buurtkaart, terugschakelen.
Gebruik: .venv/bin/python tests/test_nieuw.py"""
import os
from playwright.sync_api import sync_playwright
U = 'file://' + os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'regiokaart-midden-holland.html')
ok, mis = [], []
def check(n, c, i=''):
    (ok if c else mis).append(n); print(('  ok   ' if c else '  FOUT ') + n, '' if c else i)
with sync_playwright() as p:
    b = p.chromium.launch(); ctx = b.new_context(viewport={'width': 1440, 'height': 900}, accept_downloads=True)
    ctx.add_init_script("try{localStorage.setItem('regiokaart-rondleiding-v1','1')}catch(e){}")
    pg = ctx.new_page(); fout = []; pg.on('pageerror', lambda e: fout.append(str(e)))
    pg.goto(U); pg.wait_for_timeout(2500)
    check('knop Nieuwe huisstijl in de oude balk', pg.is_visible('#btnNieuw'))
    pg.click('#btnNieuw'); pg.wait_for_timeout(800)
    check('nieuwe weergave: balk links, oud paneel weg', pg.is_visible('#nwRail') and not pg.is_visible('#panel') and not pg.is_visible('#wissel'))
    check('regiokaartje als logo', pg.evaluate("!!document.querySelector('#nwLogo svg.vg-kaartje')"))
    check('zoekveld verplaatst', pg.evaluate("!!document.querySelector('#nwZoek #zoek')"))
    pg.click('#nwThemaKnop'); pg.wait_for_timeout(300)
    n = pg.evaluate("document.querySelectorAll('#nwCatalogus [data-k]').length"); check('catalogus met alle thema’s', n > 100, n)
    pg.fill('#nwThemaZoek', 'eenzaam'); pg.wait_for_timeout(200)
    check('thema zoeken filtert', 0 < pg.evaluate("document.querySelectorAll('#nwCatalogus [data-k]').length") < 6)
    pg.click('#nwCatalogus [data-k=ggd_eenzaam]'); pg.wait_for_timeout(500)
    check('thema kiezen', pg.evaluate("$('theme').value") == 'ggd_eenzaam' and 'Eenzaamheid' in pg.inner_text('#nwThemaKnop'))
    check('programma’s in het themapaneel', pg.evaluate("!!document.querySelector('#nwPanelen #secProg')"))
    pg.click('#nwRail [data-p=lagen]'); pg.wait_for_timeout(300)
    check('lagenpaneel met de echte lagen', pg.is_visible('#nwPanelen #secLagen') and pg.is_visible('#nwPanelen #secAchtergrond'))
    pg.check('#lyrRail'); pg.wait_for_timeout(300); check('laag aanzetten werkt', pg.evaluate("map.hasLayer(railLayer)"))
    pg.click('#nwRail [data-p=lagen]'); pg.wait_for_timeout(200); check('nogmaals klikken sluit het paneel', not pg.is_visible('#nwPaneel'))
    pg.evaluate("(()=>{const l=buurtLayer.getLayers().find(l=>l.feature.properties.buurtnaam==='Nieuwe Markt e.o.'); l.fire('click',{latlng:l.getBounds().getCenter(), originalEvent:{}});})()"); pg.wait_for_timeout(400)
    check('compacte buurtkaart in plaats van pop-up', pg.is_visible('#nwBuurt') and not pg.query_selector('.leaflet-popup') and 'Nieuwe Markt' in pg.inner_text('#nwBuurt'))
    check('vergelijking met gemeente, regio, NL', all(x in pg.inner_text('#nwBuurt') for x in ['Gouda', 'Regio', 'Nederland']))
    pg.click('#nwAlles'); pg.wait_for_timeout(200); check('alle cijfers uitklappen', pg.is_visible('#nwAllesVak .pop'))
    pg.click('#nwRail [data-p=delen]'); pg.wait_for_timeout(300)
    with pg.expect_download() as d: pg.click('#btnMapPng')
    check('download vanuit het Delen-paneel', d.value.suggested_filename.endswith('.png'))
    pg.wait_for_timeout(500); check('in de link', 'stijl=nieuw' in pg.evaluate('location.hash'))
    pg.click('#nwBw'); pg.wait_for_timeout(300); check('Brede welvaart opent', pg.is_visible('#bw')); pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
    pg.click('#nwVgl'); pg.wait_for_timeout(300); check('Vergelijken opent', pg.is_visible('#vgl')); pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
    pg.click('#nwOud'); pg.wait_for_timeout(800)
    check('terug naar oud: alles terug op zijn plek', pg.is_visible('#panel') and pg.evaluate("!!document.querySelector('#panel #secLagen') && !!document.querySelector('#panel #zoek') && !!document.querySelector('#panel #secProg') && document.querySelectorAll('.nw-plek').length===0"))
    check('geen JS-fouten', not fout, fout)
    m = b.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True).new_page(); m.goto(U); m.wait_for_timeout(1500)
    check('mobiel: geen knop', not m.is_visible('#btnNieuw'))
    b.close()
print(f'{len(ok)} goed, {len(mis)} fout'); print('fouten:', mis)
