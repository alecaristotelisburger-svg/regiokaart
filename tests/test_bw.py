"""Test van Brede welvaart: thermometer, onderbouwing, thermostaat en PDF's. Gebruik: .venv/bin/python tests/test_bw.py"""
import os, json
from playwright.sync_api import sync_playwright
UIT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'uit'); os.makedirs(UIT, exist_ok=True)
U = 'file://' + os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'regiokaart-midden-holland.html')
ok, mis = [], []
def check(n, c, i=''):
    (ok if c else mis).append(n); print(('  ok   ' if c else '  FOUT ') + n, '' if c else i)
with sync_playwright() as p:
    b = p.chromium.launch(); ctx = b.new_context(viewport={'width': 1440, 'height': 900}, accept_downloads=True)
    ctx.add_init_script("try{localStorage.setItem('regiokaart-rondleiding-v1','1')}catch(e){}")
    pg = ctx.new_page(); fout = []; pg.on('pageerror', lambda e: fout.append(str(e)))
    pg.goto(U); pg.wait_for_timeout(1500)
    pg.click('#btnBW'); pg.wait_for_timeout(400)
    check('venster open', pg.is_visible('#bw'))
    check('11 dimensies', len(pg.query_selector_all('tr.bw-dim')) == 11)
    check('uitlegblok met regiokaartje', pg.is_visible('.bw-kop h3') and pg.is_visible('.bw-kop-kaart .vg-kaartje'))
    check('Brede welvaart staat voor Tekenen', pg.evaluate("[...document.querySelectorAll('#wissel .tekenknop')].map(b=>b.id).join()").startswith('btnBW,btnVergelijken,btnTekenen'))
    check('6 gebieden (regio + 5 gemeenten)', pg.evaluate("document.querySelectorAll('.bw-tabel:not(.bw-vooruit) thead th').length") == 9)
    check('elke cel heeft 3 vakjes', pg.evaluate("[...document.querySelectorAll('tr.bw-dim .bw-vak')].every(v=>v.children.length===3)"))
    check('geen totaalcijfer', 'totaal' not in pg.inner_text('.bw-tabel').lower())
    pg.click('tr.bw-dim[data-d=veiligheid]'); pg.wait_for_timeout(200)
    check('onderbouwing klapt uit', pg.is_visible('.bw-ind') and 'misdrijven' in pg.inner_text('.bw-ind').lower())
    check('geen ervaren onveiligheid meer', 'onveilig' not in pg.inner_text('.bw-detail').lower() and len(pg.query_selector_all('.bw-detail .bw-ind tr')) == 4)
    pg.click('.bw-kaart[data-k=pol_totaal]'); pg.wait_for_timeout(500)
    check('op de kaart: thema gezet en venster dicht', pg.evaluate("$('theme').value") == 'pol_totaal' and not pg.is_visible('#bw'))
    pg.click('#btnBW'); pg.click('[data-tab=thermostaat]'); pg.click('[data-nieuw=duurzaam]')
    pg.fill('[data-p=duurzaam][data-v=naam]', 'Testbesluit'); pg.select_option('[data-p=duurzaam][data-v=trede]', '4'); pg.wait_for_timeout(200)
    opg = pg.evaluate("JSON.parse(localStorage.getItem('regiokaart-thermostaat-v1')).programmas.duurzaam")
    check('thermostaat bewaard', opg == [{'naam': 'Testbesluit', 'trede': 4}], opg)
    with pg.expect_download() as d: pg.click('#tsBewaarBestand')
    pad = os.path.join(UIT, 'thermostaat.json'); d.value.save_as(pad); check('thermostaat als bestand', json.load(open(pad))['programmas']['duurzaam'][0]['trede'] == 4)
    pg.click('[data-tab=thermometer]'); pg.wait_for_timeout(200)
    check('thermostaat-strook toont het besluit', pg.evaluate("document.querySelectorAll('.ts-strip .ts-v i').length") == 1)
    pg.click('[data-tab=uitleg]'); check('uitleg met drie regels', pg.evaluate("document.querySelectorAll('.bw-uitleg ol li').length") == 3)
    pg.click('[data-tab=thermometer]')
    with pg.expect_download() as d: pg.click('#bwPdfRegio')
    d.value.save_as(os.path.join(UIT, 'brede-welvaart-regio.pdf')); check('PDF regio', d.value.suggested_filename.endswith('.pdf'))
    import fitz
    check('PDF regio is één pagina', len(fitz.open(os.path.join(UIT, 'brede-welvaart-regio.pdf'))) == 1)
    check('alleen de knop Download als PDF', pg.inner_text('#bwPdfRegio')=='Download als PDF' and not pg.query_selector('#bwGm'))
    pg.keyboard.press('Escape'); pg.wait_for_timeout(200); check('Esc sluit', not pg.is_visible('#bw'))
    check('geen JS-fouten', not fout, fout)
    m = b.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True).new_page(); m.goto(U); m.wait_for_timeout(1500)
    check('mobiel: geen knop', not m.is_visible('#btnBW'))
    b.close()
print(f'{len(ok)} goed, {len(mis)} fout'); print('fouten:', mis)
